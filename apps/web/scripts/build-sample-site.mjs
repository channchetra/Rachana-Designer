#!/usr/bin/env node
/**
 * Generate the design.md sample site into `public/sample-site/`.
 *
 * The site source lives in `src/features/samples/` as typed modules so the same
 * definitions serve three purposes:
 *
 *  1. this script writes a browsable, multi-page project into `public/`, which
 *     the app can seed as a demo project and which can be opened directly in a
 *     browser,
 *  2. the wireframe gallery imports the page sections as insertable templates,
 *  3. the tests can assert against the generated markup.
 *
 * Deriving all three from one source is what stops the samples from drifting.
 *
 * Usage:  node scripts/build-sample-site.mjs
 */

import { mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "sample-site");

/**
 * Bundle the TS sources to a temporary ESM file so this Node script can import
 * them without a second TypeScript toolchain.
 *
 * `govDesignSystem.css` is imported with Vite's `?raw` suffix, which esbuild
 * does not understand natively — the plugin below resolves that suffix to the
 * file's text, matching Vite's behaviour exactly.
 */
async function loadSampleModule() {
  const cssRawPlugin = {
    name: "css-raw",
    setup(pluginBuild) {
      pluginBuild.onResolve({ filter: /\?raw$/ }, (args) => ({
        path: join(args.resolveDir, args.path.replace(/\?raw$/, "")),
        namespace: "css-raw",
      }));
      pluginBuild.onLoad({ filter: /.*/, namespace: "css-raw" }, async (args) => {
        const { readFile } = await import("node:fs/promises");
        const text = await readFile(args.path, "utf8");
        return { contents: `export default ${JSON.stringify(text)};`, loader: "js" };
      });
    },
  };

  const result = await build({
    entryPoints: [join(root, "src", "features", "samples", "govSite.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
    logLevel: "silent",
    plugins: [cssRawPlugin],
  });
  const code = result.outputFiles[0].text;
  const dataUrl = `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`;
  return import(dataUrl);
}

const mod = await loadSampleModule();
const pages = mod.buildSampleSite();
const index = mod.SAMPLE_PAGES.map((p) => p.file);

if (existsSync(outDir)) rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

let totalBytes = 0;
for (const page of pages) {
  const path = join(outDir, page.file);
  writeFileSync(path, page.html, "utf8");
  totalBytes += Buffer.byteLength(page.html, "utf8");
  console.log(`  ${page.file.padEnd(22)} ${(Buffer.byteLength(page.html, "utf8") / 1024).toFixed(1)} kB`);
}

// A README in the folder so a reader knows what they are looking at.
writeFileSync(
  join(outDir, "README.md"),
  `# Government sample site

Ten linked pages built to the \`design.md\` Cambodia Government Web Design System.

Generated by \`scripts/build-sample-site.mjs\` from \`src/features/samples/\`.
Open \`index.html\` in a browser, or open this folder in Rachana Designer to edit
every page visually.

| Page | Purpose |
| --- | --- |
| \`index.html\` | Homepage, following the §14/§70 blueprint |
| \`services.html\` | Public service listing (§39) |
| \`service-detail.html\` | Single service with steps, documents and contact (§40) |
| \`news.html\` | News listing (§41) |
| \`news-article.html\` | News article with breadcrumbs and related items (§42) |
| \`knowledge.html\` | Digital knowledge library and documents (§43/§38) |
| \`about.html\` | Department overview, mandate and structure (§44) |
| \`faq.html\` | FAQ accordion with grouping (§45) |
| \`contact.html\` | Contact details, map and form (§46/§31) |
| \`404.html\` | Not-found page (§64) |

All content is placeholder text. Figures carry a source and period note, and
fields the specification forbids inventing (fees, processing times) are omitted
rather than filled in — see \`design.md\` §69.
`,
  "utf8"
);

console.log(
  `\nbuild-sample-site: ${pages.length} pages, ${(totalBytes / 1024).toFixed(1)} kB total → public/sample-site/`
);
